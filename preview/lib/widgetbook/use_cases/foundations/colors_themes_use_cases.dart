@widgetbook.UseCase(name: 'Seed explorer', type: MorphTheme, path: _path)
Widget seedExplorerUseCase(BuildContext context) {
  final seed = context.knobs.object.dropdown<String>(
    label: 'seed preset',
    options: morphSeedPresets.keys.toList(),
    initialOption: morphDefaultSeedName,
  );
  final hex = context.knobs.string(label: 'custom hex (#RRGGBB)');
  final resolved = resolveSeed(seed, hex);
  final light = buildMorphTheme(resolved, Brightness.light);
  final dark = buildMorphTheme(resolved, Brightness.dark);
  return Stage(
    children: [
      for (final data in [light, dark])
        StageSection(
          title: '${data.brightness.name} scheme from this seed',
          note: 'A nested MorphTheme overrides the scope for this subtree.',
          child: MorphTheme(
            data: data,
            child: Builder(
              builder: (context) {
                final scheme = MorphTheme.of(context).colorScheme;
                return DecoratedBox(
                  decoration: BoxDecoration(
                    color: scheme.surface,
                    borderRadius: BorderRadius.circular(20),
                  ),
                  child: Padding(
                    padding: const EdgeInsets.all(16),
                    child: StageWrap(
                      children: [
                        MorphButton.filled(
                          onPressed: () {},
                          label: const Text('Filled'),
                        ),
                        MorphButton.tonal(
                          onPressed: () {},
                          label: const Text('Tonal'),
                        ),
                        MorphButton.outlined(
                          onPressed: () {},
                          label: const Text('Outlined'),
                        ),
                        MorphButton.text(
                          onPressed: () {},
                          child: const Text('Text'),
                        ),
                        MorphSwitch(value: true, onChanged: (_) {}),
                        MorphCheckbox(value: true, onChanged: (_) {}),
                      ],
                    ),
                  ),
                );
              },
            ),
          ),
        ),
    ],
  );
}

@widgetbook.UseCase(
  name: 'Adaptive theme scope',
  type: MorphThemeScope,
  path: _path,
)
Widget adaptiveThemeScopeUseCase(BuildContext context) {
  final seed = resolveSeed(
    context.knobs.object.dropdown<String>(
      label: 'seed preset',
      options: morphSeedPresets.keys.toList(),
      initialOption: morphDefaultSeedName,
    ),
    '',
  );
  final initialDark = context.knobs.boolean(label: 'initial dark');
  return _AdaptiveScopeHarness(
    key: resetKey([seed, initialDark]),
    seed: seed,
    initialDark: initialDark,
  );
}

/// Hosts a real [MorphThemeScope] driven by a [MorphThemeController].
class _AdaptiveScopeHarness extends StatefulWidget {
  const _AdaptiveScopeHarness({
    super.key,
    required this.seed,
    required this.initialDark,
  });

  final Color seed;
  final bool initialDark;

  @override
  State<_AdaptiveScopeHarness> createState() => _AdaptiveScopeHarnessState();
}

class _AdaptiveScopeHarnessState extends State<_AdaptiveScopeHarness> {
  final MorphThemeController _controller = MorphThemeController();

  @override
  void dispose() {
    _controller.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final data = MorphThemeData.light(seedColor: widget.seed);
    return MorphThemeScope(
      baseData: data,
      controller: _controller,
      initialTheme: widget.initialDark ? Brightness.dark : Brightness.light,
      child: Builder(
        builder: (context) {
          final morph = MorphTheme.of(context);
          final controller = MorphTheme.controllerOf(context);
          return ColoredBox(
            color: morph.colorScheme.surface,
            child: Stage(
              children: [
                StageSection(
                  title: 'MorphThemeScope (${morph.brightness.name})',
                  note:
                      'The controller switches brightness without rebuilding '
                      'the app; components follow the resolved theme.',
                  child: StageWrap(
                    children: [
                      MorphButton.filled(
                        onPressed: () => controller?.toggleBrightness(
                          fallback: morph.brightness,
                        ),
                        label: const Text('Toggle brightness'),
                      ),
                      MorphButton.outlined(
                        onPressed: () => controller?.followSystem(),
                        label: const Text('Follow system'),
                      ),
                    ],
                  ),
                ),
                StageSection(
                  title: 'Components inside the scope',
                  child: StageWrap(
                    children: [
                      MorphCard.filled(
                        child: const Padding(
                          padding: EdgeInsets.all(20),
                          child: Text('Card in the adaptive scope'),
                        ),
                      ),
                      MorphSwitch(value: true, onChanged: (_) {}),
                    ],
                  ),
                ),
              ],
            ),
          );
        },
      ),
    );
  }
}

@widgetbook.UseCase(
