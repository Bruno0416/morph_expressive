class _Swatch extends StatelessWidget {
  const _Swatch({
    required this.name,
    required this.color,
    required this.onColor,
  });

  final String name;
  final Color color;
  final Color onColor;

  @override
  Widget build(BuildContext context) {
    final outline = MorphTheme.of(context).colorScheme.outlineVariant;
    return Container(
      width: 148,
      height: 72,
      padding: const EdgeInsets.all(10),
      alignment: Alignment.bottomLeft,
      decoration: BoxDecoration(
        color: color,
        borderRadius: BorderRadius.circular(16),
        border: Border.all(color: outline),
      ),
      child: Text(
        name,
        style: TextStyle(color: onColor, fontSize: 12, height: 1.2),
      ),
    );
  }
}

