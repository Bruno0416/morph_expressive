  return Stage(
    children: [
      StageSection(
        title: 'MorphComponentTheme',
        note:
            'Rebuilds its subtree from the resolved Morph theme, which is how '
            'component wrappers read tokens.',
        child: MorphComponentTheme(
          builder: (context) {
            final morph = MorphTheme.of(context);
            return Text(
              'primary = #${(morph.colorScheme.primary.toARGB32() & 0xFFFFFF).toRadixString(16).padLeft(6, '0')} · '
              'brightness = ${morph.brightness.name}',
              style: morph.textTheme.bodyLarge,
            );
          },
        ),
      ),
      StageSection(
        title: 'MorphResolvedTheme',
        note: 'Projects a MorphThemeData onto the Material Theme as well.',
        child: MorphResolvedTheme(
          data: buildMorphTheme(
            const Color(0xFF00897B),
            MorphTheme.of(context).brightness,
          ),
          child: Builder(
            builder: (context) => StageWrap(
              children: [
                MorphButton.filled(
                  onPressed: () {},
                  label: Text(
                    'Teal resolved theme',
                    style: Theme.of(context).textTheme.labelLarge,
                  ),
                ),
              ],
            ),
          ),
        ),
      ),
      StageSection(
        title: 'MorphMaterialApp / MorphDynamicColorHost',
        note:
            'This workbench wraps every use case in a Material app with '
            'MorphTheme and MorphMotionScope (the same scope MorphMaterialApp '
