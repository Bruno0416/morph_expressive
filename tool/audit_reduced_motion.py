#!/usr/bin/env python3
"""Run the whole component suite with controlled motion accessibility flags.

Regression checks for normal and reduced-motion behavior; failures are never hidden.
No production source, pubspec, dependency resolution or lockfile is rewritten.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
MARKER = 'MORPH_MOTION_TRACE '


def inventory() -> dict:
    owners = {}
    families = {}
    for directory in sorted((ROOT / 'lib/components').iterdir()):
        if not directory.is_dir():
            continue
        files = []
        for path in sorted(directory.rglob('*.dart')):
            source = path.read_text()
            for name in re.findall(r'\bclass\s+(Morph\w+)', source):
                owners[name] = directory.name
            signals = sorted(set(re.findall(
                r'\b(?:AnimationController|SingleMotionController|MotionBuilder|'
                r'SingleMotionBuilder|Animated[A-Z]\w*|Timer|Ticker)\b', source)))
            if signals:
                files.append({
                    'path': str(path.relative_to(ROOT)),
                    'signals': signals,
                    # This is a source observation, never proof of compliance.
                    'direct_preference_read': bool(re.search(
                        r'disableAnimations|DisableAnimations|reduceMotion|ReduceMotion', source)),
                })
        families[directory.name] = {'animation_sources': files}
    target = ROOT / 'test/support/motion_component_owners.dart'
    target.parent.mkdir(parents=True, exist_ok=True)
    generated = (
        '// Generated by tool/audit_reduced_motion.py --inventory.\n'
        '// Component ownership only; presence does not establish motion compliance.\n'
        'const motionComponentOwners = <String, String>{\n' +
        ''.join(f"  '{name}': '{family}',\n" for name, family in sorted(owners.items())) +
        '};\n')
    if not target.exists() or target.read_text() != generated:
        temporary = target.with_suffix('.tmp')
        temporary.write_text(generated)
        temporary.replace(target)
    catalog = [{'family': family, 'name': name} for family, name in re.findall(
        r"MorphCatalogEntry\('([^']+)', '([^']+)'\)",
        (ROOT / 'preview/lib/component_catalog.dart').read_text()) if family != 'foundation']
    return {'families': families, 'component_owners': owners, 'public_catalog': catalog}


def parse_events(path: Path) -> dict:
    tests = {}
    outcomes = {}
    errors = []
    traces = []
    for line in path.read_text(errors='replace').splitlines():
        try:
            event = json.loads(line)
        except (ValueError, TypeError):
            continue
        kind = event.get('type')
        if kind == 'testStart':
            tests[event['test']['id']] = event['test']
        elif kind == 'testDone' and not event.get('hidden', False):
            outcomes[event['testID']] = event
        elif kind == 'error':
            errors.append({'testID': event.get('testID'), 'error': event.get('error'),
                           'stackTrace': event.get('stackTrace')})
        elif kind == 'print':
            message = event.get('message', '')
            if message.startswith(MARKER):
                trace = json.loads(message[len(MARKER):])
                trace['testID'] = event.get('testID')
                traces.append(trace)
    results = []
    for identifier, outcome in outcomes.items():
        test = tests.get(identifier, {})
        if test.get('name', '').startswith('loading '):
            continue
        results.append({'name': test.get('name', str(identifier)),
                        'result': outcome.get('result'), 'skipped': outcome.get('skipped', False)})
    return {'tests': results, 'errors': errors, 'traces': traces}


def write_report(output: Path, source: dict, runs: list[dict]) -> dict:
    observed = {name for run in runs for trace in run['traces']
                for names in trace.get('mounted', {}).values() for name in names}
    catalog_coverage = [dict(item, mounted=item['name'] in observed)
                        for item in source['public_catalog']]
    summary = {'inventory': source, 'runs': runs, 'families': {},
               'public_catalog_coverage': catalog_coverage}
    for family in source['families']:
        cells = {}
        for run in runs:
            traces = [t for t in run['traces'] if family in t.get('mounted', {})]
            animations = [a for t in traces for a in t['animations'] if a['family'] == family]
            cells[f"{run['scope']}/{run['profile']}"] = {
                'widget_tests_mounted': len(traces),
                'mounted_components': sorted({n for t in traces for n in t['mounted'][family]}),
                'observed_active_animations': sum(a['activeSamples'] > 0 for a in animations),
                'observed_reduced_motion_over_80ms': [a for a in animations
                    if a['activeReducedSamples'] > 0 and a['maxActiveAgeMs'] >= 80
                    and a['valueChanges'] > 0],
            }
        summary['families'][family] = cells
    (output / 'summary.json').write_text(json.dumps(summary, indent=2) + '\n')
    lines = [
        '# Morph Expressive — reduced motion audit', '',
        '## Scope and interpretation', '',
        '- Full: disableAnimations=false, reduceMotion=false.',
        '- Reduced (combined web-style flags): disableAnimations=true, reduceMotion=true.',
        '- Optional reduce-only (separate platform flag): disableAnimations=false, reduceMotion=true.',
        '- accessibleNavigation remains false; screen-reader navigation is a separate preference.',
        '- Catalog tests mount all 39 families and change preferences while mounted. '
        'They verify lifecycle and flag propagation, not every interaction or visual variant.',
        '- The existing suite supplies interactions; dedicated motion contracts inspect '
        'intermediate geometry. Those contracts fail if decorative motion violates the reduced-motion policy.',
        '- Observed motion over 80ms is a review candidate, not an automatic accessibility failure. '
        'Scrolling, dragging and essential progress require individual interpretation.',
        '- Unobserved motion is not a pass: merged/private listenables, painters/timers and '
        'transitions between pumps may escape the passive sampler.',
        '- Widget tests do not replace Firefox/Chrome, renderer, GPU or native-device validation.',
        '', '## Executed runs', '',
        '| Scope | Profile | Pass | Fail | Skip | Exit | Seconds |',
        '|---|---|---:|---:|---:|---:|---:|',
    ]
    for run in runs:
        counts = {result: sum(t['result'] == result and not t['skipped'] for t in run['tests'])
                  for result in ['success', 'failure', 'error']}
        skipped = sum(t['skipped'] for t in run['tests'])
        lines.append(f"| {run['scope']} | {run['profile']} | {counts['success']} | "
                     f"{counts['failure'] + counts['error']} | {skipped} | {run['exit_code']} | "
                     f"{run['seconds']:.1f} |")
    lines += ['', '## Family coverage and observations', '',
              '| Family | Mounted widget tests | Components observed | Reduced motion >80ms |',
              '|---|---:|---:|---:|']
    for family, cells in summary['families'].items():
        lines.append(f"| {family} | {sum(c['widget_tests_mounted'] for c in cells.values())} | "
                     f"{len({n for c in cells.values() for n in c['mounted_components']})} | "
                     f"{sum(len(c['observed_reduced_motion_over_80ms']) for c in cells.values())} |")
    mounted = sum(item['mounted'] for item in catalog_coverage)
    lines += ['', '## Public catalog component coverage', '',
              f'{mounted}/{len(catalog_coverage)} public catalog widget classes were dynamically observed.',
              'This counts mounted classes, not constructor variants or all their behavior.', '']
    for item in catalog_coverage:
        if not item['mounted']:
            lines.append(f"- Not observed: {item['family']}/{item['name']}")
    lines += ['', '## Failing tests', '']
    for run in runs:
        for test in run['tests']:
            if test['result'] != 'success' and not test['skipped']:
                lines.append(f"- **{run['scope']}/{run['profile']}**: {test['name']}")
    lines += ['', 'See summary.json for exact per-family observations, test results, '
              'errors and traces. Raw *.jsonl files retain the Flutter JSON reporter output.', '']
    (output / 'REPORT.md').write_text('\n'.join(lines))
    return summary


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--flutter', default='flutter')
    parser.add_argument('--profiles', nargs='+', choices=['full', 'reduced', 'reduce-only'],
                        default=['full', 'reduced'])
    parser.add_argument('--scope', choices=['library', 'contracts', 'preview', 'catalog', 'all'], default='all')
    parser.add_argument('--output', type=Path, default=ROOT / '.dart_tool/motion_audit')
    parser.add_argument('--inventory', action='store_true')
    parser.add_argument('--concurrency', type=int, default=2)
    args = parser.parse_args()
    source = inventory()
    if args.inventory:
        print(f"Inventory: {len(source['families'])} families, {len(source['component_owners'])} component classes")
        return 0
    flutter = shutil.which(args.flutter)
    if flutter is None:
        parser.error('Flutter SDK is required; pass --flutter /absolute/path/to/flutter')
    flutter = str(Path(flutter).resolve())
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    scopes = ['library', 'contracts', 'preview', 'catalog'] if args.scope == 'all' else [args.scope]
    runs = []
    for scope in scopes:
        cwd = ROOT if scope in {'library', 'contracts'} else ROOT / 'preview'
        if not (cwd / '.dart_tool/package_config.json').exists():
            parser.error(f'Run flutter pub get in {cwd} before auditing')
        target = {'library': 'test', 'contracts': 'test/audits/motion_contracts.dart',
                  'preview': 'test', 'catalog': 'test/audits/motion_catalog.dart'}[scope]
        for profile in args.profiles:
            log = output / f'{scope}-{profile}.jsonl'
            targets = [target]
            if scope == 'contracts':
                targets.append('test/audits/motion_auxiliary_catalog.dart')
            if scope == 'catalog':
                targets.append('test/audits/motion_carousel_catalog.dart')
            command = [flutter, 'test', *targets, '--no-pub', '--reporter=json',
                       f'--concurrency={args.concurrency}',
                       f'--dart-define=MORPH_MOTION_AUDIT_PROFILE={profile}']
            print(f'Running {scope}/{profile} -> {log}', flush=True)
            started = time.monotonic()
            env = dict(os.environ, CI='true', FLUTTER_SUPPRESS_ANALYTICS='true')
            with log.open('w') as stream:
                result = subprocess.run(command, cwd=cwd, env=env, stdout=stream,
                                        stderr=subprocess.STDOUT, check=False)
            run = {'scope': scope, 'profile': profile, 'command': command,
                   'exit_code': result.returncode, 'seconds': time.monotonic() - started,
                   'log': log.name, **parse_events(log)}
            runs.append(run)
            write_report(output, source, runs)
            print(f"Finished {scope}/{profile}: exit={result.returncode}, tests={len(run['tests'])}", flush=True)
    missing = [family for family, cells in write_report(output, source, runs)['families'].items()
               if not any(c['widget_tests_mounted'] for c in cells.values())]
    enforce_coverage = args.scope in {'all', 'catalog'}
    if missing and enforce_coverage:
        print('Families not dynamically mounted: ' + ', '.join(missing), file=sys.stderr)
    print(f'Report: {output / "REPORT.md"}')
    return int((bool(missing) and enforce_coverage) or any(r['exit_code'] for r in runs))


if __name__ == '__main__':
    raise SystemExit(main())
